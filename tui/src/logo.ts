export type Mark = number[][];

// Labels every lit pixel with its figure (-1 for empty), figures numbered clockwise from the top.
export function figures(rows: readonly string[]): Mark {
  const mark: Mark = rows.map((row) => [...row].map(() => -1));
  const centers: { id: number; x: number; y: number }[] = [];
  let next = 0;
  rows.forEach((row, y) =>
    [...row].forEach((pixel, x) => {
      if (pixel !== "#" || mark[y]![x] !== -1) {
        return;
      }
      const id = next++;
      const stack = [[x, y]];
      let sumX = 0;
      let sumY = 0;
      let count = 0;
      while (stack.length > 0) {
        const [px, py] = stack.pop()!;
        if (rows[py!]?.[px!] !== "#" || mark[py!]![px!] !== -1) {
          continue;
        }
        mark[py!]![px!] = id;
        sumX += px!;
        sumY += py!;
        count += 1;
        stack.push([px! + 1, py!], [px! - 1, py!], [px!, py! + 1], [px!, py! - 1]);
      }
      centers.push({ id, x: sumX / count, y: sumY / count });
    }),
  );
  const midX = (rows[0]!.length - 1) / 2;
  const midY = (rows.length - 1) / 2;
  const turn = (c: { x: number; y: number }) => (Math.atan2(c.x - midX, midY - c.y) + 2 * Math.PI) % (2 * Math.PI);
  const order = new Map([...centers].sort((a, b) => turn(a) - turn(b)).map((c, index) => [c.id, index]));
  return mark.map((row) => row.map((id) => (id === -1 ? -1 : (order.get(id) ?? 0))));
}

// Halves the mark for small terminals: a pixel is lit when any of its 2x2 block is.
export function shrink(mark: Mark): Mark {
  const out: Mark = [];
  for (let y = 0; y < mark.length; y += 2) {
    const row: number[] = [];
    for (let x = 0; x < mark[y]!.length; x += 2) {
      const block = [mark[y]![x], mark[y]![x + 1], mark[y + 1]?.[x], mark[y + 1]?.[x + 1]];
      row.push(Math.max(...block.map((id) => id ?? -1)));
    }
    out.push(row);
  }
  return out;
}
